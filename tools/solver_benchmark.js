#!/usr/bin/env node
// Measures the hint's solver (FreeCellCore.analyse, the same code the game runs in its Web Worker)
// on the warm-up deals and a sample of every tier, from the deal's start, and checks every line it
// returns against the game's move rule. Writes docs/SOLVER_BENCHMARK.md.
//   node tools/solver_benchmark.js [deals per tier, default 100]
// "Phone" columns use a quarter of the time budget: a slow phone runs JavaScript about 4× slower
// than a desktop PC, so this estimates what the default budget gives there.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const assets = path.join(root, 'app/src/main/assets');
const html = fs.readFileSync(path.join(assets, 'freecell.html'), 'utf8');
const block = html.slice(html.indexOf('/* freecell-core:start'), html.indexOf('/* freecell-core:end */'));
const core = new Function(`${block}; return FreeCellCore;`)();
const catalog = core.cleanCatalog(JSON.parse(fs.readFileSync(path.join(assets, 'deal_catalog.json'), 'utf8')));
const config = core.normalizeConfig({});
const perTier = Number(process.argv[2]) || 100;

const deal = seed => ({ tableau: core.dealTableau(seed), cells: [null, null, null, null], foundations: [0, 0, 0, 0] });
const spread = (list, n) => Array.from({ length: Math.min(n, list.length) }, (_, i) => list[Math.floor(i * list.length / Math.min(n, list.length))]);
const medium = [];
for (let n = 7; medium.length < perTier; n += 613) if (core.tierOf(catalog, n) === 'medium') medium.push(n);
const groups = {
  'Warm-up': config.difficulty.first_games.seeds,
  Easy: spread(catalog.easy, perTier),
  Medium: medium,
  Hard: spread(catalog.hard, perTier),
};

function measure(seeds, timeLimitMs) {
  const times = [];
  let solved = 0, unsolvable = 0;
  for (const seed of seeds) {
    const started = process.hrtime.bigint();
    const result = core.runToEnd(core.analyse(deal(seed), { maxNodes: config.hint.node_limit, timeLimitMs }));
    times.push(Number(process.hrtime.bigint() - started) / 1e6);
    if (result.status === 'unsolvable') unsolvable++;
    if (result.status !== 'solved') continue;
    let state = deal(seed);
    for (const move of result.line) {
      if (!core.canMove(state, move)) throw new Error(`#${seed}: the line has a move the game refuses`);
      state = core.applyMove(state, move);
    }
    if (!state.foundations.every(value => value === 13)) throw new Error(`#${seed}: the line does not win`);
    solved++;
  }
  times.sort((a, b) => a - b);
  const at = share => times[Math.min(times.length - 1, Math.floor(share * times.length))];
  return { count: seeds.length, solved, unsolvable, median: at(0.5), p90: at(0.9), max: times[times.length - 1] };
}

const budget = config.hint.time_budget_ms, phone = Math.round(budget / 4);
const rows = Object.entries(groups).map(([name, seeds]) => {
  const pc = measure(seeds, budget), slow = measure(seeds, phone);
  const pct = (part, whole) => `${Math.round(100 * part / whole)}%`;
  const ms = value => `${value < 10 ? value.toFixed(1) : Math.round(value)} ms`;
  console.log(name, pc, slow);
  return `| ${name} | ${pc.count} | ${pct(pc.solved, pc.count)} | ${ms(pc.median)} | ${ms(pc.p90)} | ${ms(pc.max)} | ${pct(slow.solved, slow.count)} |`;
});
const text = `# Hint solver benchmark

Generated by \`node tools/solver_benchmark.js ${perTier}\` on ${new Date().toISOString().slice(0, 10)} (Node ${process.version}, desktop PC).
Each deal is analysed from its start with the default \`hint_config\` budget (${budget} ms,
${config.hint.node_limit.toLocaleString('en')} positions), as the Hint button does. Every line found was replayed through the
game's move rule (\`FreeCellCore.canMove\`) to a win.

| Deals | Count | Line found | Median | 90% | Max | Line found with ${phone} ms ("slow phone") |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

Notes:

- A deal start is the hardest moment: later in a game the search space is much smaller, and the
  background analysis after each move usually has the answer ready before the player taps Hint.
- When no line is found within the budget the hint falls back to the best guess and nothing is
  claimed; only an exhaustive search reports a lost position.
- Real phone times come from the debug timing log (DEV panel, row "Solver", and \`[solver]\` lines
  in logcat).
`;
fs.writeFileSync(path.join(root, 'docs/SOLVER_BENCHMARK.md'), text);
console.log('docs/SOLVER_BENCHMARK.md written');

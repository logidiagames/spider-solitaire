#!/usr/bin/env node
// Writes docs/REMOTE_CONFIG_ALL.md: every Remote Config parameter with its bundled default, ready
// to paste into the Firebase console. Run it after changing a *_defaults.json file:
//   node tools/write_remote_config_all.js
// app/src/test/js/core.test.mjs fails when the document no longer matches the bundled defaults.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const assets = path.join(root, 'app/src/main/assets');
// Parameter name → bundled default file and the document with the details.
const PARAMETERS = [
  ['ads_config', 'ad_config_defaults.json', 'REMOTE_CONFIG_ADS.md'],
  ['config_admbob_mediator', 'config_admbob_mediator_defaults.json', 'REMOTE_CONFIG_ADS.md'],
  ...['progression_config', 'daily_challenge_config', 'economy_config', 'themes_config', 'daily_bonus_config', 'missions_config',
    'remove_ads_config', 'rating_config', 'store_config', 'events_config', 'rewarded_config', 'notifications_config', 'stars_config',
    'achievements_config', 'difficulty_config', 'rivals_config', 'hint_config', 'tips_config', 'feel_config', 'languages_config', 'performance_config'].map(key => [key, `${key}_defaults.json`, 'REMOTE_CONFIG_GAME.md']),
];

const sections = PARAMETERS.map(([key, file, doc]) => {
  const json = JSON.stringify(JSON.parse(fs.readFileSync(path.join(assets, file), 'utf8')));
  return `## \`${key}\`\n\nDetails: \`docs/${doc}\`. Bundled default (\`assets/${file}\`):\n\n\`\`\`json\n${json}\n\`\`\`\n`;
});
const text = `# All Remote Config parameters

Every Firebase Remote Config parameter the app reads, each a JSON string, with the value the app
ships with. Paste a block as the parameter's value to publish the defaults; the app checks every
value again and falls back field by field. Remote values apply on the next launch.

Generated by \`tools/write_remote_config_all.js\` from the bundled defaults; do not edit by hand.

${sections.join('\n')}`;
fs.writeFileSync(path.join(root, 'docs/REMOTE_CONFIG_ALL.md'), text);
console.log(`docs/REMOTE_CONFIG_ALL.md: ${PARAMETERS.length} parameters`);
